/**
 * Regenerates docs/commands.md from the registered slash-command definitions
 * and COMMAND_POLICIES.   Usage: pnpm docs:commands
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ApplicationCommandOptionType, type APIApplicationCommandOption } from 'discord-api-types/v10';
import { COMMAND_POLICIES } from '@gynx/permissions';
import { modules } from '../apps/bot/src/modules';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');

const TYPE: Partial<Record<ApplicationCommandOptionType, string>> = {
  [ApplicationCommandOptionType.String]: 'text',
  [ApplicationCommandOptionType.Integer]: 'integer',
  [ApplicationCommandOptionType.Number]: 'number',
  [ApplicationCommandOptionType.Boolean]: 'true/false',
  [ApplicationCommandOptionType.User]: 'user',
  [ApplicationCommandOptionType.Channel]: 'channel',
  [ApplicationCommandOptionType.Role]: 'role',
  [ApplicationCommandOptionType.Mentionable]: 'mentionable',
  [ApplicationCommandOptionType.Attachment]: 'file',
};

function optionLine(o: APIApplicationCommandOption): string {
  const req = 'required' in o && o.required ? '' : ' _(optional)_';
  const choices = 'choices' in o && o.choices?.length ? ` — one of: ${o.choices.map((c) => `\`${c.name}\``).join(', ')}` : '';
  const auto = 'autocomplete' in o && o.autocomplete ? ' (autocomplete)' : '';
  return `\`${o.name}\` (${TYPE[o.type] ?? 'value'}${auto})${req}: ${o.description}${choices}`;
}

const out: string[] = [
  '# Slash command reference',
  '',
  '> Generated by `pnpm docs:commands` from the command definitions. Do not edit by hand.',
  '',
  'All commands are guild-only and work only in the configured GYNX.GG server. Replies to members are ephemeral unless noted by the command. Staff commands are hidden from members by Discord default permissions, and every command is re-authorized server-side. See [permissions.md](permissions.md).',
  '',
];

for (const m of modules) {
  const cmds = m.commands ?? [];
  if (cmds.length === 0) continue;
  out.push(`## ${m.name[0]!.toUpperCase()}${m.name.slice(1)}`, '');
  for (const c of [...cmds].sort((a, b) => a.data.name.localeCompare(b.data.name))) {
    const p = COMMAND_POLICIES[c.data.name];
    const perm = p?.permission ? `requires \`${p.permission}\`` : 'any member';
    const rl = p?.rateLimit ? ` · limit ${p.rateLimit[0]} per ${p.rateLimit[1]}s` : '';
    out.push(`### \`/${c.data.name}\``, '', `${c.data.description}  `, `_${perm}${rl} · module \`${c.module}\`_`, '');
    const opts = (c.data.options ?? []) as APIApplicationCommandOption[];
    const subs = opts.filter((o) => o.type === ApplicationCommandOptionType.Subcommand || o.type === ApplicationCommandOptionType.SubcommandGroup);
    if (subs.length) {
      for (const s of subs) {
        if (s.type === ApplicationCommandOptionType.SubcommandGroup) {
          for (const ss of s.options ?? []) {
            out.push(`- **\`${s.name} ${ss.name}\`**: ${ss.description}`);
            for (const o of ss.options ?? []) out.push(`  - ${optionLine(o as APIApplicationCommandOption)}`);
          }
        } else {
          out.push(`- **\`${s.name}\`**: ${s.description}`);
          for (const o of (s as { options?: APIApplicationCommandOption[] }).options ?? []) out.push(`  - ${optionLine(o)}`);
        }
      }
    } else if (opts.length) {
      for (const o of opts) out.push(`- ${optionLine(o)}`);
    }
    out.push('');
  }
}

writeFileSync(resolve(root, 'docs/commands.md'), out.join('\n'));
console.log(`Wrote docs/commands.md (${modules.flatMap((m) => m.commands ?? []).length} commands)`);
